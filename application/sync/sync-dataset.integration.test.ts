import { afterEach, beforeAll, describe, expect, it } from "vitest";
import { eq } from "drizzle-orm";
import { db, schema } from "@/infrastructure/db/client";
import { registerConnector } from "@/infrastructure/connectors/registry";
import { syncDataset } from "./sync-dataset";
import { resetDb } from "@/test/integration/db-helpers";
import type { RemoteDataset, RemoteItemPage, SourceConnector } from "@/domain/sync/ports";

/**
 * In-memory fake standing in for the Apify connector, registered under the
 * "manual" source kind (never used by a real adapter) so `syncDataset` exercises
 * its real probe/ingest/cursor logic against a real database without any network
 * call. `items` is mutated between `syncDataset()` calls within a test to simulate
 * new upstream items appearing.
 */
function fakeConnector(): SourceConnector & {
  items: Record<string, unknown>[];
  modifiedAt: Date;
} {
  const state = {
    items: [] as Record<string, unknown>[],
    // Fixed unless a test bumps it — a real upstream only moves `modifiedAt` when
    // its content actually changes, and the probe-skip test below depends on that.
    modifiedAt: new Date("2026-01-01T00:00:00.000Z"),
    kind: "manual",
    async listDatasets(): Promise<RemoteDataset[]> {
      return [];
    },
    async getDataset(externalId: string): Promise<RemoteDataset | null> {
      return {
        externalId,
        name: "fake",
        title: "fake",
        itemCount: state.items.length,
        createdAt: new Date("2026-01-01T00:00:00.000Z"),
        modifiedAt: state.modifiedAt,
        producerId: null,
        producerRunId: null,
      };
    },
    async fetchItems(_externalId: string, offset: number, limit: number): Promise<RemoteItemPage> {
      const page = state.items.slice(offset, offset + limit);
      return { items: page, total: state.items.length, offset, limit };
    },
  };
  return state;
}

async function seedDatasetAndProfile() {
  const [source] = await db()
    .insert(schema.sources)
    .values({ kind: "manual", name: `sync-test-source-${crypto.randomUUID()}` })
    .returning();

  await db()
    .insert(schema.mappingProfiles)
    .values({
      name: `sync-test-profile-${crypto.randomUUID()}`,
      sourceKind: "manual",
      rules: {
        externalId: { from: ["id"] },
        body: { from: ["text"] },
        postedAt: { from: ["time"], transform: "toIso8601" },
      },
      matchPaths: ["id", "text"],
      passthrough: true,
      autoGenerated: false,
      confidence: 1,
      approvedAt: new Date(),
    });

  const [dataset] = await db()
    .insert(schema.datasets)
    .values({ sourceId: source.id, externalId: "fake-dataset-1", syncCursor: {} })
    .returning();

  return dataset.id;
}

describe("syncDataset resumability", () => {
  beforeAll(async () => {
    await resetDb();
  });
  afterEach(async () => {
    await resetDb();
  });

  it("advances the watermark cursor by exactly what it ingested", async () => {
    const connector = fakeConnector();
    registerConnector(connector);
    connector.items = [
      { id: "a", text: "looking to buy a villa", time: "2026-01-01T00:00:00.000Z" },
      { id: "b", text: "want to buy land", time: "2026-01-01T01:00:00.000Z" },
    ];

    const datasetId = await seedDatasetAndProfile();
    const outcome = await syncDataset(datasetId, "manual", { force: true });

    expect(outcome.status).toBe("succeeded");
    expect(outcome.itemsNew).toBe(2);

    const [row] = await db()
      .select({ syncCursor: schema.datasets.syncCursor })
      .from(schema.datasets)
      .where(eq(schema.datasets.id, datasetId));
    expect((row.syncCursor as { lastOffset?: number }).lastOffset).toBe(2);
  });

  it("resumes from the committed offset instead of reprocessing already-ingested items", async () => {
    const connector = fakeConnector();
    registerConnector(connector);
    connector.items = [
      { id: "a", text: "looking to buy a villa", time: "2026-01-01T00:00:00.000Z" },
      { id: "b", text: "want to buy land", time: "2026-01-01T01:00:00.000Z" },
    ];

    const datasetId = await seedDatasetAndProfile();
    await syncDataset(datasetId, "manual", { force: true });

    // Simulate more items landing upstream between runs.
    connector.items = [
      ...connector.items,
      { id: "c", text: "budget around $200k for a house", time: "2026-01-01T02:00:00.000Z" },
    ];
    connector.modifiedAt = new Date("2026-01-01T02:00:00.000Z");

    const second = await syncDataset(datasetId, "manual", { force: true });

    // Only the one genuinely new item should be counted — the cursor must not
    // cause "a"/"b" to be re-read and double-counted as new.
    expect(second.itemsNew).toBe(1);

    const leads = await db().select().from(schema.leads).where(eq(schema.leads.datasetId, datasetId));
    expect(leads).toHaveLength(3);
  });

  it("skips the run entirely when nothing changed upstream and force is not set", async () => {
    const connector = fakeConnector();
    registerConnector(connector);
    connector.items = [{ id: "a", text: "looking to buy a villa", time: "2026-01-01T00:00:00.000Z" }];

    const datasetId = await seedDatasetAndProfile();
    await syncDataset(datasetId, "manual", { force: true });

    const outcome = await syncDataset(datasetId, "cron");
    expect(outcome.status).toBe("skipped");
    expect(outcome.itemsSeen).toBe(0);
  });
});

describe("auto-approved mapping profile quality guardrail", () => {
  beforeAll(async () => {
    await resetDb();
  });
  afterEach(async () => {
    await resetDb();
  });

  it("revokes a freshly auto-approved mapping profile whose first batch is mostly spam", async () => {
    const connector = fakeConnector();
    registerConnector(connector);
    // Field names ("id"/"text"/"time") are exact synonym matches, so proposeMapping
    // auto-approves with high confidence — no curated profile is seeded, forcing
    // that path. Every item trips the spam lexicon so intent is never "buyer".
    connector.items = Array.from({ length: 6 }, (_, i) => ({
      id: `spam-${i}`,
      text: "make money online fast, click the link in bio, forex trading signals",
      time: "2026-01-01T00:00:00.000Z",
    }));

    const [source] = await db()
      .insert(schema.sources)
      .values({ kind: "manual", name: `quality-test-source-${crypto.randomUUID()}` })
      .returning();
    const [dataset] = await db()
      .insert(schema.datasets)
      .values({ sourceId: source.id, externalId: "quality-dataset-1", syncCursor: {} })
      .returning();

    const outcome = await syncDataset(dataset.id, "manual", { force: true });
    expect(outcome.status).toBe("succeeded");

    const [updatedDataset] = await db()
      .select({ mappingProfileId: schema.datasets.mappingProfileId })
      .from(schema.datasets)
      .where(eq(schema.datasets.id, dataset.id));
    expect(updatedDataset.mappingProfileId).not.toBeNull();

    const [profile] = await db()
      .select()
      .from(schema.mappingProfiles)
      .where(eq(schema.mappingProfiles.id, updatedDataset.mappingProfileId!));

    expect(profile.autoGenerated).toBe(true);
    // Auto-approved at insert time, then revoked once the first batch proved suspect.
    expect(profile.approvedAt).toBeNull();

    // The next sync must not keep normalizing through a revoked mapping.
    connector.items.push({ id: "spam-6", text: "more forex signals", time: "2026-01-01T01:00:00.000Z" });
    connector.modifiedAt = new Date("2026-01-01T01:00:00.000Z");
    const second = await syncDataset(dataset.id, "manual", { force: true });
    expect(second.leadsCreated).toBe(0);
  });

  it("leaves a healthy freshly auto-approved profile approved", async () => {
    const connector = fakeConnector();
    registerConnector(connector);
    connector.items = Array.from({ length: 6 }, (_, i) => ({
      id: `buyer-${i}`,
      text: `looking to buy a villa in Canggu, budget around $${200 + i}k, whatsapp me`,
      time: "2026-01-01T00:00:00.000Z",
    }));

    const [source] = await db()
      .insert(schema.sources)
      .values({ kind: "manual", name: `quality-test-source-${crypto.randomUUID()}` })
      .returning();
    const [dataset] = await db()
      .insert(schema.datasets)
      .values({ sourceId: source.id, externalId: "quality-dataset-2", syncCursor: {} })
      .returning();

    await syncDataset(dataset.id, "manual", { force: true });

    const [updatedDataset] = await db()
      .select({ mappingProfileId: schema.datasets.mappingProfileId })
      .from(schema.datasets)
      .where(eq(schema.datasets.id, dataset.id));
    const [profile] = await db()
      .select()
      .from(schema.mappingProfiles)
      .where(eq(schema.mappingProfiles.id, updatedDataset.mappingProfileId!));

    expect(profile.approvedAt).not.toBeNull();
  });
});
